# «включи/поставь музыку, джаз, группу X, альбом Y» — музыка из открытых каталогов
# (Internet Archive). None = фраза не про это; "" = про музыку, но без запроса
# (тогда сервер переспросит жанр/исполнителя).
_MUSIC_IA = re.compile(
    r"^(?:включи|поставь|запусти|вруби|давай|хочу послушать|послушаем|включи-ка)\s+"
    r"(?:музыку\s+|музыка\s+|музычка\s+|альбом\s+|альбомчик\s+|группу\s+|группа\s+|"
    r"песни\s+|песню\s+|треки?\s+|исполнителя\s+|что-нибудь\s+из\s+)?"
    r"(.+?)\.?$", re.I)
# ASR отдаёт фразу в исходной форме: «включи Басту» (вин. падеж), а поиск по
# сайтам хочет именительный («Баста»). Правила среза флексий — в _nominative.


def _nominative(q: str) -> str:
    """Срезает ТОЛЬКО винительные флексии -у/-ю -> -а/-я («Басту»->«Баста»,
    «Земфиру»->«Земфира», «войну»->«война»).

    Родительные -а/-я НЕ трогаем: «льва» и «война» — легитимные формы
    (женский именительный «война» ломался срезом: «война и мир» -> «войн и мир»,
    живой баг 03.11 «Не нашла аудиокнигу Льва Толстого»). Родительный падеж
    поисковики терпят не всегда: SkySound на «моргенштерна» отдаёт чужую
    «Песню про Моргенштерна», поэтому -а срезаем ТОЛЬКО для слов >= 7 символов
    (у коротких -а почти всегда женский именительный).
    """
    words = q.split()
    out = []
    for w in words:
        lw = w.lower()
        if not lw.isascii() and len(w) >= 4 and lw[-1] in "ую":
            w = w[:-1] + ("а" if lw[-1] == "у" else "я")
        # ВАЖНО: ветки «-а/-я у слов от 7 букв» здесь больше НЕТ. Она срезала последнюю
        # букву у нормальных имён в именительном: «Земфира» -> «Земфир», «Пятница» ->
        # «Пятниц» (проверено 06.11). Родительный «моргенштерна» поисковики переживают,
        # а испорченное имя собственное — нет.
        out.append(w)
    return " ".join(out)
# бытовые команды, которые НЕ должны уходить в музыкальный поиск
# (фильм/сериал/новости/подкаст/громкость/звук добавлены 19.11: «включи фильм»,
# «включи подкаст», «включи громкость» искали треки и глушили облако в relay)
_NOT_MUSIC = re.compile(
    r"\b(свет|люстр|телевизор|пылесос|кондиционер|вентилятор|чайник|кофе|воду|будильник|"
    r"таймер|громкость|звук|громче|тише|блютуз|bluetooth|вай-?фай|wi-?fi|книгу|книга|"
    r"радио|новости|погод|таймер|секундомер|фильм|сериал|подкаст|видео)\b", re.I)
# «кино» здесь НЕТ намеренно: это ещё и группа («включи кино группа крови»).
_GENRES = ("джаз", "рок", "блюз", "классик", "электрон", "эмбиент", "фолк", "рэп",
           "хип-хоп", "поп", "метал", "соул", "фанк", "регги", "шансон", "романс",
           "бардовск", "инструментал")


def match_music_ia(text: str) -> str | None:
    """Музыка из открытых каталогов -> строка-запрос ("" = уточнить у пользователя)."""
    t = _norm(text)
    # команды плеера («поставь на паузу», «пауза», «дальше», «стоп») — НЕ поиск:
    # иначе «пауза» уезжала в каталог как имя исполнителя
    if re.search(r"\b(паузу|пауза|паузе|стоп|хватит|дальше|следующ|предыдущ|продолжи"
                 r"|продолжай|возобнови|что играет|громче|тише|громкость)\b", t):
        return None
    if _NOT_MUSIC.search(t):
        return None
    # запрос берём из ИСХОДНОГО текста (регистр важен: SkySound ищет «Кино»,
    # а не «кино»), а guard-ы выше — по нормализованному (чтобы ловить команды)
    m = _MUSIC_IA.match(text.strip())
    if m:
        q = m.group(1).strip()
        # «пожалуйста» на конце — вежливость, не часть запроса (раньше
        # «включи пожалуйста» искало исполнителя «пожалуйст»); знаки препинания
        # по краям — тоже не часть запроса («Включи группу Кино!» -> «Кино»)
        q = re.sub(r"[\s,]+пожалуйста[.!?\s]*$", "", q, flags=re.I)
        q = q.strip(" .!?,;:")
        if not q or _norm(q) == "пожалуйста":
            return ""  # «включи, пожалуйста» — без имени, переспросим
        # «включи музыку» без уточнения — переспросим
        if q in ("музыку", "музыка", "музычка", "что-нибудь"):
            return ""
        return _nominative(q)
    words = t.split()
    # Жанр — только ОТДЕЛЬНЫМ СЛОВОМ и только в короткой фразе, которая не вопрос.
    # Раньше сравнивали подстрокой: «поп» ловился внутри «популярная», и вопрос
    # «какая сейчас самая популярная новогодняя песня?» уходил в поиск музыки и
    # включал треки вместо ответа (живой случай 06.11). Так же «рок» ловился в
    # «урок», «поп» — в «попробуй».
    if (len(words) <= 4 and not text.strip().endswith("?")
            and not re.search(r"\b(как|какой|какая|какие|что|кто|почему|сколько|где|когда|"
                              r"расскажи|подскажи|скажи)\b", t)
            and re.match(r"^(?:хочу|давай|поставь|включи)?\s*\S", t)):
        for g in _GENRES:
            if re.search(rf"(?<!\w){re.escape(g)}(?!\w)", t):
                return t.replace("хочу", "").replace("давай", "").strip() or g
    return None


_PODCAST = re.compile(
    r"(?:включи|поставь|запусти|найди|вруби)\s+(?:подкаст|подкасты)\s*(?:про|о|об)?\s*(.+?)\.?$",
    re.I)
_PODCAST_BARE = re.compile(r"^(?:включи|поставь)\s+подкаст\.?$", re.I)


def match_podcast(text: str) -> str | None:
    """«включи подкаст про историю» -> запрос; «включи подкаст» -> "" (уточним)."""
    t = text.strip()
    m = _PODCAST.match(t)
    if m:
        return m.group(1).strip()
    if _PODCAST_BARE.match(t):
        return ""
    return None


# «включи книгу что-нибудь» — запрос пустой: переспросить, какую книгу, а не
# искать книгу с названием «что нибудь» (аудит 22.11).
_BOOK_EMPTY = {"мне", "что нибудь", "чего нибудь", "какую нибудь"}


def match_book(text: str) -> tuple[str, str] | None:
    """Команда про аудиокнигу -> (действие, запрос). Действия: play | resume.

    «включи книгу война и мир» -> ("play", "война и мир")
    «почитай мастера и маргариту» -> ("play", "мастера и маргарита")
    «продолжай книгу» -> ("resume", "")
    «включи книгу» без названия -> ("play", "") — Router переспросит какую
    """
    t = re.sub(r"^(алиса|слушай алиса)\s+", "", _norm(text))
    if not t:
        return None
    # «включи книгу»/«включи аудиокнигу» без названия — ПЕРЕСПРОСИТЬ, а не None
    # (иначе фраза падала в match_music и искала музыку «книгу»).
    bare = re.sub(r" пожалуйста$", "", t).strip()
    if re.fullmatch(rf"({_BOOK_START}|{_BOOK_READ})\s+(?:мне\s+)?{_BOOK_OBJ}", bare):
        return "play", ""
    if _RESUME.match(t):
        return "resume", ""
    core = re.sub(rf"^({_BOOK_START}|{_BOOK_READ})\s+", "", t)
    if core == t:
        return None  # глагол не книжный
    core = re.sub(r"^мне\s+", "", core)          # «почитай мне X» -> X
    core = re.sub(r" (?:пожалуйста|пж)$", "", core).strip()
    if not core:
        return "play", ""   # «включи книгу»/«почитай» — переспросить какую
    # Стоп-слова сверяем ПОСЛЕ откусывания объекта: «включи книгу что-нибудь» —
    # это пустой запрос, а не книга с названием «что нибудь» (аудит 22.11).
    m = re.match(rf"^{_BOOK_OBJ}\s+(.+)$", core)
    if m:
        rest = re.sub(r" (?:пожалуйста|пж)$", "", m.group(2)).strip()
        if not rest or rest in _BOOK_EMPTY:
            return "play", ""
        return "play", _nominative(rest)
    if re.fullmatch(rf"{_BOOK_OBJ}", core):
        return "play", ""
    # Без объекта книги «включи что-нибудь» — это НЕ книга (пусть идёт в
    # музыку/волну); с глаголом чтения — переспрос, какую книгу почитать.
    if core in _BOOK_EMPTY:
        if re.match(rf"^({_BOOK_READ})\b", t):
            return "play", ""
        return None
    # «почитай X» — глагол чтения сам по себе implies книгу
    if re.match(rf"^({_BOOK_READ})\b", t):
        return "play", _nominative(core)
    return None


# ------------------------------------------------------------------ таймеры

@dataclass
class TimerCommand:
    """Команда управления таймером/будильником. Выполняется в uniproxy через TimerService."""
    action: str = ""        # add_timer | cancel_timer | list | add_alarm | cancel_alarm
    seconds: int = 0
    label: str = ""
    hour: int = 0
    minute: int = 0
    days: tuple = ()
    repeat: bool = False


_UNITS_SEC = {
    "секунд": 1, "секунды": 1, "секунду": 1, "сек": 1,
    "минут": 60, "минуты": 60, "минуту": 60, "мин": 60,
    "час": 3600, "часа": 3600, "часов": 3600,
}

# порядковые числительные для «полвосьмого», «половина девятого»
_ORDINALS = {
    "первого": 1, "второго": 2, "третьего": 3, "четвертого": 4, "пятого": 5,
    "шестого": 6, "седьмого": 7, "восьмого": 8, "девятого": 9, "десятого": 10,
    "одиннадцатого": 11, "двенадцатого": 12,
    "первой": 1, "второй": 2, "третьей": 3, "четвертой": 4, "пятой": 5,
    "шестой": 6, "седьмой": 7, "восьмой": 8, "девятой": 9, "десятой": 10,
}
_DAYPARTS = {
    "утра": "am", "утром": "am", "утру": "am", "день": "pm", "дня": "pm", "днем": "pm",
    "вечера": "pm", "вечером": "pm", "ночи": "night", "ночью": "night",
}

# Слова-повтора, содержащие «день»/«дню» зря: «каждый день в 7:30» раньше
# парсилось как «дня» -> pm и будильник ставился на 19:30 (живой баг 18.11).
# Вырезаем эти фразы ДО разбора времени.
_REPEAT_WORDS = re.compile(
    r"\b(?:каждый\s+день|каждое\s+утро|каждую\s+ночь|ежедневно|по\s+будням|"
    r"по\s+выходным|день\s+рождения)\b", re.I)


def _strip_repeat(t: str) -> str:
    return " ".join(_REPEAT_WORDS.sub(" ", t).split())


def _num_from_token(w: str):
    """Число из токена: цифра или слово. Возвращает float|None."""
    if w.isdigit():
        return float(w)
    return _UNITS.get(w)


def _parse_duration(t: str) -> tuple[float, str] | None:
    """«пять минут»/«двадцать пять минут»/«час»/«полтора часа» -> (секунды, описание).

    Числа копим в буфер; встретив единицу измерения, умножаем сумму буфера на неё.
    Единица без числа («на час») считается как 1.
    """
    total = 0.0
    found: list[str] = []
    buf: list[str] = []
    buf_val = 0.0
    for raw in re.split(r"\s+", t):
        w = raw.strip(".,!?")
        if not w:
            continue
        if w in ("пол", "половина"):
            # «пол часа» = 30 минут. Раньше «пол» не считалось числом, а единица без
            # числа трактовалась как 1 — выходил целый час.
            buf.append(w)
            buf_val += 0.5
            continue
        if w == "полчаса":
            # слитное «полчаса» — 30 минут (раньше фраза не распознавалась вовсе)
            total += 1800
            found.append("полчаса")
            continue
        if w == "полминуты":
            total += 30
            found.append("полминуты")
            continue
        if w == "полторачаса":
            total += 5400
            found.append("полтора часа")
            continue
        unit = _UNITS_SEC.get(w)
        if unit is not None:
            mult = buf_val if buf else 1.0
            total += mult * unit
            found.append((" ".join(buf) + " " if buf else "") + w)
            buf, buf_val = [], 0.0
            continue
        n = _num_from_token(w)
        if n is not None:
            buf.append(w)
            buf_val += n
    if not found or total <= 0:
        return None
    return total, "на " + " ".join(found)


def _parse_clock(t: str) -> tuple[int, int] | None:
    """«семь утра»/«7 утра»/«18:30»/«шесть тридцать»/«полвосьмого» -> (hour, minute)."""
    m = re.search(r"\b(\d{1,2}):(\d{2})\b", t)
    if m:
        hh, mm = int(m.group(1)), int(m.group(2))
        # «25:99» — не время: раньше возвращалось (1, 99), и add_alarm падал
        # ValueError внутри обработчика («Не смог настроить таймер»)
        if 0 <= hh <= 23 and 0 <= mm <= 59:
            return hh, mm
    # «будильник в полдень / в полночь»
    if re.search(r"\bполдень\b", t):
        return 12, 0
    if re.search(r"\bполночь\b|\bв полночь\b", t):
        return 0, 0
    # «на 7 часов 30 минут»: раньше ранний час-регекс возвращал (7, 0), и
    # «30 минут» терялись — будильник звонил в 07:00 вместо 07:30.
    m = re.search(r"\b(\d{1,2})\s*(?:час|часа|часов)\b(?:\s+(\d{1,2})\s*(?:мин\w*)?)?", t)
    if m:
        h = int(m.group(1)) % 24
        mi = int(m.group(2)) if m.group(2) and 0 <= int(m.group(2)) <= 59 else 0
        return _apply_daypart(h, mi, t)
    # «будильник на час ночи» / «в час дня» — час без числа. Раньше это уходило в
    # таймер на 60 минут («поставь будильник на час ночи» -> таймер 3600 с).
    if re.search(r"\b(?:на|в)\s+час(?:а|ов)?(?:\s|$)", t):
        return _apply_daypart(1, 0, t)

    # «полвосьмого», «пол-восьмого», «половина девятого» — половина N-го часа = (N-1):30
    m = re.search(r"\bпол(?:овина)?\s?-?([а-яё]+)\b", t)
    if m:
        w = m.group(1)
        n = _ORDINALS.get(w) or _UNITS.get(w)
        if n:
            return _apply_daypart((int(n) - 1) % 24, 30, t)

    # «шесть тридцать», «семь сорок пять», «восемь ноль пять», «двадцать три пятьдесят восемь»
    words = re.findall(r"\b(?:[а-яё]+|\d{1,2})\b", t)
    nums = [(i, _num_from_token(w)) for i, w in enumerate(words) if _num_from_token(w) is not None]
    if nums:
        # часы могут идти двумя словами («двадцать три» = 23): складываем подряд идущие,
        # но ТОЛЬКО когда первое слово — десяток. Иначе «16:06» (после _norm это
        # «16 06») склеивалось в 22:00, и «будильник на 16:06» звонил в десять вечера.
        h = int(nums[0][1])
        pos = 1
        first_word = words[nums[0][0]]
        if (first_word in _TENS and len(nums) > 1 and nums[1][0] == nums[0][0] + 1
                and 0 <= h + int(nums[1][1]) <= 23 and int(nums[1][1]) <= 9):
            h = h + int(nums[1][1])
            pos = 2
        mi = 0
        if len(nums) > pos and nums[pos][0] == nums[pos - 1][0] + 1:
            mi = int(nums[pos][1])
            # минуты тоже могут идти двумя словами: «сорок пять» = 45, «ноль пять» = 05
            if len(nums) > pos + 1 and nums[pos + 1][0] == nums[pos][0] + 1:
                mi += int(nums[pos + 1][1])
        if 0 <= h <= 23 and 0 <= mi <= 59:
            return _apply_daypart(h, mi, t)
    return None


def _apply_daypart(h: int, mi: int, t: str) -> tuple[int, int]:
    """Корректирует час по словам «утра/вечера/ночи/дня»."""
    part = None
    for w, p in _DAYPARTS.items():
        if re.search(rf"\b{w}\b", t):
            part = p
            break
    if part == "am" and h == 12:
        h = 0
    elif part == "pm" and h < 12:
        h += 12
    elif part == "night":
        # «ночь»: 12 -> полночь, 1-4 -> как есть (час ночи = 01:00), 9-11 -> вечер
        # (десять ночи = 22:00), 5-8 -> раннее утро (пять ночи = 05:00).
        # Раньше ЛЮБОЕ 5-11 уводило в PM: «пять ночи» ставило будильник на 17:00.
        if h == 12:
            h = 0
        elif 9 <= h <= 11:
            h += 12
    return h % 24, mi


def _parse_weekdays(t: str) -> tuple:
    days = tuple(sorted({_WEEKDAYS[w] for w in re.findall(r"\b[а-яё]+\b", t) if w in _WEEKDAYS}))
    return days


_TIMER_START = (r"(поставь|поставьте|включи|запусти|создай|сделай|заведи|установи|добавь|напомни"
                r"|разбуди|подними)"
                r"|(таймер|секундомер)\b")


def match_timer(text: str) -> TimerCommand | None:
    """Голосовые команды таймеров и будильников. None — это не таймерная команда."""
    t = _norm(text)
    t = re.sub(r"^(алиса|олег|мистер жопосранчик)\s+", "", t)
    t = re.sub(r"\s+", " ", t).strip()
    if not t:
        return None

    # guard: слово должно встречаться в любой форме («таймер», «таймера», «таймеру»…)
    is_timer_word = bool(re.search(r"\b(таймер|секундомер)\w*", t))
    is_alarm_word = bool(re.search(r"\b(будильник|подъем|подьем)\w*", t))
    # «отмени всё» — без слова «таймер», но это частая команда отмены; её решает uniproxy
    # (если отменять нечего, фраза уйдёт дальше в музыку/LLM)
    is_cancel_all = bool(re.search(r"\b(отмени|отменить|выключи|сними|сбрось)\s+(всё|все|всех)\b", t))
    if not (is_timer_word or is_alarm_word or is_cancel_all or re.match(_TIMER_START, t)):
        return None

    # ---- отмена
    if re.search(r"\b(отмени|отменить|выключи|убери|сними|останови|прекрати|сбрось)\b", t):
        if is_alarm_word and not is_timer_word:
            return TimerCommand(action="cancel_alarm")
        if is_timer_word:
            return TimerCommand(action="cancel_timer")
        # «отмени всё» без упоминания таймера: пробуем снять таймеры и будильники.
        # Если их нет, uniproxy вернёт None и фраза уйдёт дальше (музыка/LLM).
        if re.search(r"\b(всё|все|всех)\b", t):
            return TimerCommand(action="cancel_all")
        return TimerCommand(action="cancel_timer")

    # ---- список / сколько осталось
    # «сколько у меня таймеров», «какие таймеры стоят», «есть ли активные будильники» и т.п.
    # Ключевые слова могут разделяться («есть ли активные таймеры») — допускаем .* между ними.
    _t_alarm = r"(таймер|будильник)"
    if re.search(rf"(сколько.*{_t_alarm}|{_t_alarm}\w*.*сколько|какие.*{_t_alarm}|"
                 rf"{_t_alarm}\w*\s+(стоят|есть|активны|заданы|поставлены)|список.*{_t_alarm}|"
                 rf"что с {_t_alarm}|покажи.*{_t_alarm}|есть ли.*{_t_alarm}|котор.*{_t_alarm})", t):
        return TimerCommand(action="list")

    # ---- будильник
    # «будильник на семь утра», а также разговорное «поставь на шесть утра» /
    # «заведи на семь тридцать» — без слова «будильник», но с явным временем суток.
    # Медиа-фразы («поставь музыку на семь утра») не трогаем — их ведёт match_music.
    _MEDIA = r"(музык|песн|трек|альбом|плейлист|радио|фильм|сериал|видео|подкаст)"
    # «поставь таймер на 7» — это НЕ будильник, хотя глагол «поставь» из _TIMER_START
    # подходил и раньше ставил будильник на 7:00. Если сказано «таймер» и не сказано
    # «будильник» — ветку будильника пропускаем.
    if ((is_alarm_word or (re.match(_TIMER_START, t) and not is_timer_word))
            and not re.search(_MEDIA, t)):
        # «каждый день/по будням/день рождения» вырезаем ДО разбора времени:
        # «день» из повтора ловился как «дня» -> pm, и «будильник на каждый
        # день в 7:30» ставился на 19:30 (живой баг 18.11).
        t_clock = _strip_repeat(t)
        # Относительный будильник: «разбуди через 10 минут», «будильник через
        # два часа», и «будильник на 10 минут» (только минуты/секунды, без часа
        # и без времени суток) — время = now + длительность.
        rel = _relative_alarm(t_clock, is_alarm_word)
        if rel is not None:
            days = _parse_weekdays(t_clock)
            return TimerCommand(action="add_alarm", hour=rel[0], minute=rel[1],
                                days=days, repeat=bool(days), label="будильник")
        clock = _parse_clock(t_clock)
        if clock and (is_alarm_word or _looks_like_alarm(t_clock)):
            days = _parse_weekdays(t)
            repeat = bool(re.search(r"\b(каждый день|ежедневно|по будням|повтор|каждую)\b", t)) or bool(days)
            if re.search(r"\bпо будням\b", t):
                days = (0, 1, 2, 3, 4)
            elif re.search(r"\bпо выходным\b", t):
                days, repeat = (5, 6), True
            h, mi = clock
            # время в label не пишем: list_str подставит его сам («будильник на 07:00»)
            label = "будильник каждый день" if repeat else "будильник"
            return TimerCommand(action="add_alarm", hour=h, minute=mi, days=days, repeat=repeat,
                                label=label)

    # ---- таймер
    # Медиа-фразы не трогаем: «поставь музыку на 5 минут» — это команда плееру
    # (спать через 5 минут), а не таймер. Раньше глагол «поставь» из _TIMER_START
    # превращал такую фразу в таймер на 5 минут, и музыка не включалась.
    if re.search(_MEDIA, t):
        return None
    dur = _parse_duration(t)
    if dur:
        seconds = int(round(dur[0]))
        if 0 < seconds <= 24 * 3600:
            return TimerCommand(action="add_timer", seconds=seconds, label=f"таймер {dur[1]}")
    # «поставь таймер на 7» — единицу не назвали, но разговорно это минуты
    if is_timer_word and not is_alarm_word:
        m = re.search(r"\b(?:на|за)\s+(\d{1,3})\b", t)
        if m:
            seconds = int(m.group(1)) * 60
            if 0 < seconds <= 24 * 3600:
                return TimerCommand(action="add_timer", seconds=seconds,
                                    label=f"таймер на {m.group(1)} минут")
    return None


def _relative_alarm(t: str, is_alarm_word: bool) -> tuple[int, int] | None:
    """Будильник через относительное время -> (hour, minute) по местным часам.

    «разбуди через 10 минут», «будильник через два часа», «будильник на 10 минут».
    Раньше такие фразы уходили в _parse_clock: «на 10 минут» -> будильник 10:00,
    «через два часа» -> 02:00 (живой баг 18.11).
    """
    has_through = re.search(r"\bчерез\b", t) is not None
    dur = _parse_duration(t)
    if dur is None:
        return None
    # без «через» относительным считаем только длительность, в которой нет часов
    # и нет времени суток: «будильник на 10 минут», но «будильник на 10 часов
    # вечера» — это абсолютное время.
    if not has_through:
        if not is_alarm_word:
            return None
        if re.search(r"\b(час|часа|часов)\b", t) or re.search(
                r"\b(утра|утром|утру|дня|днем|вечера|вечером|ночи|ночью|полдень|полночь)\b", t):
            return None
        if dur[0] > 3600:
            return None
    now = time.time() + dur[0]
    lt = time.localtime(now)
    return lt.tm_hour, lt.tm_min


def _looks_like_alarm(t: str) -> bool:
    """Отличает «поставь на шесть утра» (будильник) от «поставь на десять минут» (таймер).

    Будильник — когда есть слово «будильник»/«подъём», указание времени суток
    (утра/вечера/ночи/дня) или длительность не задана вовсе.
    """
    if re.search(r"\b(будильник|подъем|подьем|разбуди|напомни утром)\w*", t):
        return True
    if re.search(r"\b(утра|утром|утру|дня|днем|вечера|вечером|ночи|ночью)\b", t):
        return True
