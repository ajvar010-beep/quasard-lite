@dataclass
class IntentResult:
    text: str = ""  # что сказать (пусто — молча)
    directives: list[dict] = field(default_factory=list)
    reset_dialog: bool = False


def _norm(text: str) -> str:
    return " ".join(re.sub(r"[^\w\s]", " ", text.lower().replace("ё", "е")).split())


def _level(words: list[str]) -> int | None:
    for w in words:
        if w.isdigit():
            return int(w)
        if w in _NUMS:
            return _NUMS[w]
    return None


def match(text: str) -> IntentResult | None:
    t = _norm(text)
    t = re.sub(r"^(алиса|слушай алиса)\s+", "", t)
    words = t.split()
    if not words:
        return None

    if re.fullmatch(r"(стоп|хватит|замолчи|молчи|отмена|тихо|выключись|помолчи)( пожалуйста)?", t):
        return IntentResult()

    if re.search(r"\b(громкость|уровень громкости|поставь громкость|сделай громкость)\b", t):
        lvl = _level(words)
        # «громкость 50» / «на 50 процентов» — это ПРОЦЕНТЫ: раньше 11–100 просто
        # отбрасывалось и фраза уходила в LLM. Переводим в уровень 0–10.
        if lvl is not None and 11 <= lvl <= 100:
            lvl = max(0, min(10, round(lvl / 10)))
        if lvl is not None and 0 <= lvl <= 10:
            return IntentResult(directives=[client_action("sound_set_level",
                                                          {"new_level": lvl, "new_percent_level": lvl * 10})])
    _what = r"( музыку| музыка| звук| песню| трек)?"
    if re.fullmatch(rf"(сделай|сделать|можно)?{_what} ?(погромче|громче|прибавь|увеличь громкость|еще громче)"
                    rf"{_what}( пожалуйста)?", t):
        return IntentResult(directives=[client_action("sound_louder")])
    if re.fullmatch(rf"(сделай|сделать|можно)?{_what} ?(потише|тише|убавь|уменьши громкость|еще тише)"
                    rf"{_what}( пожалуйста)?", t):
        return IntentResult(directives=[client_action("sound_quiter")])  # именно quiter — так у Яндекса

    if re.search(r"\b(включи|запусти)\b.*\b(блютуз|bluetooth)\b", t):
        return IntentResult("Включаю блютуз.", [client_action("start_bluetooth")])
    if re.search(r"\b(выключи|отключи)\b.*\b(блютуз|bluetooth)\b", t):
        return IntentResult("Выключаю блютуз.", [client_action("stop_bluetooth")])

    if re.fullmatch(r"(давай )?(начнем сначала|новый (диалог|разговор)|забудь (все|наш разговор)|сбрось (диалог|контекст))", t):
        return IntentResult("Хорошо, начнём заново.", reset_dialog=True)
    return None


# ------------------------------------------------------------------ модель / глубокий поиск

_MODEL_Q = re.compile(
    r"(на какой|какой|что за|какая) (модели|модель|нейросети|нейросеть|ллм|llm)"
    r"( ты)? (работаешь|функционируешь|крутишься|запущена|стоит|используется)"
    r"|кто ты (такой )?по модели"
    r"|(твоя |какая у тебя )модель"
    r"|как(ая|ой) у тебя (нейросеть|ллм|llm|языковая модель)"
    r"|какую (модель|нейросеть|llm) ты используешь"
)


# Вопрос о модели: слово «модель/нейросеть/LLM» рядом с вопросом или глаголом.
# Старая регулярка требовала точного порядка («на какой модели ты работаешь») и
# пропускала «на базе какой модели ты сейчас работаешь» — фраза уходила в модель,
# и та врала («GPT-4», в логе 06.11).
_MODEL_WORD = re.compile(r"\b(модел\w*|нейросет\w*|нейронн\w*|ллм|llm)\b", re.I)
_MODEL_ASK = re.compile(
    r"\b(как\w+|что за|на базе|работа\w*|использу\w*|стоишь|крутишься|обслужива\w*)\b", re.I)


def match_model_question(text: str) -> bool:
    """«На какой модели ты работаешь?», «на базе какой модели» — отвечаем без LLM."""
    t = re.sub(r"^(алиса|слушай алиса|олег)\s+", "", _norm(text))
    return bool(_MODEL_Q.search(t) or (_MODEL_WORD.search(t) and _MODEL_ASK.search(t)))


# «Покажи свой системный промпт» — отдаём текст инструкций как есть, без модели.
# «промпт»/«промт» в обычной речи почти не встречаются, поэтому хватает самого слова;
# «правила/инструкции» — только с притяжательным, иначе поймали бы «правила игры».
_PROMPT_WORD = re.compile(r"\b(промпт|промт)\w*\b", re.I)
# «промпт» само по себе бывает и в общем вопросе («расскажи про промпты»), поэтому
# рядом должно быть указание на МЕНЯ: твой/свой/системный/покажи/какой.
_PROMPT_HINT = re.compile(
    r"\b(тво[йи]\w*|сво[йи]\w*|системн\w*|у тебя|покажи|скажи|озвучь|прочитай|"
    r"продиктуй|зачитай|какой|какие|что за)\b", re.I)
_PROMPT_OWN = re.compile(
    r"\b(системн\w+|тво[йи]\w*|сво[йи]\w*)\s+(инструкци\w+|правил\w+|установк\w+)", re.I)


def match_prompt_question(text: str) -> bool:
    """«Какой у тебя системный промпт?», «покажи свои инструкции»."""
    t = re.sub(r"^(алиса|слушай алиса|олег)\s+", "", _norm(text))
    if _PROMPT_OWN.search(t):
        return True
    return bool(_PROMPT_WORD.search(t) and _PROMPT_HINT.search(t))


_YES_RE = re.compile(
    r"^(да|ага|угу|конечно|давай|ок|окей|хорошо|ладно|согласен|согласна"
    r"|да пожалуйста|да давай|ну да|точно)( пожалуйста| давай)?[.!]?$"
)


def match_yes(text: str) -> bool:
    """Короткое согласие — «да», «давай», «конечно» (для подтверждения глубокого поиска)."""
    t = re.sub(r"^(алиса|слушай алиса)\s+", "", _norm(text))
    return bool(_YES_RE.match(t))


_DEEP_Q = re.compile(
    r"(глубоки[йм]|глубок|подробн|детальн)\w* (поиском|поиск|поищи|поройся|покопай)"
    r"|поищи глубже|покопай глубже|поройся (в интернете|в сети)"
    r"|узнай (побольше|поподробнее)|проведи глубокий поиск|глубокий поиск"
)


def match_deep_search(text: str) -> bool:
    """Явный запрос глубокого поиска: «поищи глубже», «проведи глубокий поиск»."""
    t = re.sub(r"^(алиса|слушай алиса)\s+", "", _norm(text))
    return bool(_DEEP_Q.search(t))


# ------------------------------------------------------------------ музыка

_PLAY = r"(включи|включай|поставь|запусти|сыграй|играй|давай послушаем|хочу послушать)"
_WAVE = r"(музыку|музычку|что нибудь|что-нибудь|мою волну|волну|мою музыку|любимое|радио)"


def match_music(text: str) -> tuple[str, str] | None:
    """Музыкальная команда -> (действие, запрос).

    Действия: wave, search, next, prev, pause, resume, what, like, dislike."""
    t = re.sub(r"^(алиса|слушай алиса)\s+", "", _norm(text))
    if not t:
        return None
    # «мне нравится», «эта песня мне не нравится»… — короткая фраза-оценка, а не вопрос («что тебе нравится?»)
    words = t.split()
    is_rating = len(words) <= 6 and words[0] not in ("что", "кто", "почему", "как", "какая", "какой", "какие") \
        and "тебе" not in words and not text.strip().endswith("?")
    if re.fullmatch(r"(поставь )?дизлайк|дизлайкни|убери (эту песню|этот трек)|не надо такое", t) or \
            (is_rating and re.search(r"\bне (нравится|понравилось|нравятся)\b", t)):
        return "dislike", ""
    if re.fullmatch(r"(поставь )?лайк|лайкни|добавь в (любимые|избранное|понравившиеся|мне нравится)|"
                    r"(классная|крутая|отличная) (песня|музыка|песенка)", t) or \
            (is_rating and re.search(r"\b(нравится|понравилось|нравятся)\b", t)):
        return "like", ""
    if re.fullmatch(r"(дальше|следующий( трек)?|следующую( песню)?|следующая( песня)?|переключи( трек| песню)?|"
                    r"другую( песню)?|пропусти|включи следующ\w+( трек| песню)?|некст)( пожалуйста)?", t):
        return "next", ""
    if re.fullmatch(r"(назад|предыдущ\w+( трек| песн\w+)?|верни( предыдущ\w+)?( трек| песню)?|включи предыдущ\w+( трек| песню)?)"
                    r"( пожалуйста)?", t):
        return "prev", ""
    # «поставь паузу», «поставь музыку на паузу» раньше не ловились и уходили ниже
    # в музыкальный ПОИСК (запрос «паузу»), «сделай паузу»/«приостанови» — в LLM
    _obj = r"(?:это|музыку|музыка|трек|песню|книгу|подкаст|запись|воспроизведение)"
    if re.fullmatch(rf"(?:пауза|паузу|на паузу|(?:поставь|сделай|ставь)(?: {_obj})? (?:на )?паузу|"
                    rf"(?:при)?останови(?: {_obj})?|выключи музыку)(?: пожалуйста)?", t):
        return "pause", ""
    if re.fullmatch(r"(?:продолжи|продолжай|продолжить|играй|играй дальше|сними(?: это)? с паузы|"
                    r"сними паузу|убери паузу|возобнови)(?: музыку| воспроизведение| трек| песню)?"
                    r"(?: пожалуйста)?", t):
        return "resume", ""
    if re.fullmatch(r"(что|кто) (сейчас |это )?(играет|поет|за песня|за трек)|как называется (эта )?(песня|трек)", t):
        return "what", ""
    m = re.fullmatch(_PLAY + r"( пожалуйста)?( " + _WAVE + r")?( пожалуйста)?", t)
    if m:
        return "wave", ""
    # без глагола — частый ответ в продолжении диалога: «Музыку», «Мою волну давай»
    if re.fullmatch(r"(давай |ну )?(музыку|музычку|мою волну|волну|музыка)( давай| включи| пожалуйста)?", t):
        return "wave", ""
    m = re.fullmatch(_PLAY + r"( пожалуйста)?( песню| песни| трек| альбом| группу| исполнителя| плейлист)? (.+)", t)
    if m:
        query = re.sub(r"\s+пожалуйста$", "", m.group(4)).strip()
        # не музыка: бытовая техника, фильмы, новости, подкасты, громкость/звук.
        # Раньше «включи чайник/фильм/подкаст» искали треки «чайник/фильм/подкаст»
        # (и в relay глушили облачный ответ: classify=True).
        if query and not _NOT_MUSIC.search(query):
            return "search", query
    return None


# ------------------------------------------------------------------ скорость / повтор / трек
# Скорость: «быстрее», «медленнее», «скорость полтора», «в два раза быстрее».
_SPEED_WORD = {"полтора": 1.5, "полторы": 1.5, "половина": 0.5, "пол": 0.5,
               "один": 1.0, "одна": 1.0, "два": 2.0, "две": 2.0, "три": 3.0,
               "четыре": 4.0, "пять": 5.0}


def match_speed(text: str) -> "float | str | None":
    """Команда скорости: 'faster' | 'slower' | число | 0.0 (сброс) | None.

    «в два раза быстрее» -> число 2; «быстрее» -> 'faster' (+0.25 в main);
    «нормальная скорость» -> 0.0 (главный код вернёт 1.0).

    Число берём из СЫРОГО текста: _norm превращает «1.5» в «1 5», а десятые
    доли для скорости — главный случай.
    """
    raw = text.lower().replace("ё", "е")
    t = re.sub(r"^(алиса|слушай алиса)\s+", "", _norm(text))
    mnum = re.search(r"(\d+(?:[.,]\d+)?)", raw)
    num = float(mnum.group(1).replace(",", ".")) if mnum else None

    def word_num() -> float | None:
        if num is not None:
            return num
        for w in t.split():
            if w in _SPEED_WORD:
                return _SPEED_WORD[w]
        return None

    if re.search(r"\b(нормальн\w+|обычн\w+|обыкновенн\w+)\b.*\bскорост\w*", t) or \
            re.fullmatch(r"(сбрось|верни|убери) скорость( пожалуйста)?|как обычно( скорость)?", t):
        return 0.0
    # «в два раза быстрее» — ДО голого «быстрее»
    if re.search(r"\bв\s+\S+\s+раз\w*\s+(быстрее|медленнее)", t):
        n = word_num()
        if n is not None and n > 0:
            return n if "быстрее" in t else round(1.0 / n, 3)
    if re.search(r"\bскорост\w*", t):
        return word_num()
    if re.fullmatch(r"(включи |сделай |поставь |много |немного |чуть |сильно )?"
                    r"(?:по)?быстрее( пожалуйста)?|ускорь( воспроизведение)?( пожалуйста)?", t):
        return "faster"
    if re.fullmatch(r"(включи |сделай |поставь |много |немного |чуть |сильно )?"
                    r"(?:по)?медленнее( пожалуйста)?|замедли( воспроизведение)?( пожалуйста)?", t):
        return "slower"
    return None


_ORDINAL = {"первый": 1, "первую": 1, "второй": 2, "вторую": 2, "третий": 3,
            "третью": 3, "четвертый": 4, "четвертую": 4, "пятый": 5, "пятую": 5,
            "шестой": 6, "шестую": 6, "седьмой": 7, "седьмую": 7, "восьмой": 8,
            "восьмую": 8, "девятый": 9, "девятую": 9, "десятый": 10, "десятую": 10}


def match_jump(text: str) -> int | None:
    """«включи третий трек», «поставь пятую часть», «трек номер семь» -> номер.

    Голосом глагол часто теряется: ASR отдаёт голое «третий трек» (лог
    20.11: «Алиса, включи третий трек» -> «третий трек»). Поэтому глагол
    необязателен, но тогда обязательно слово-объект (трек/песня/часть/глава/
    номер) и ровно одно число. «Включи кино», «включи двадцать два», «следующий
    трек» сюда не попадают — это поиск музыки и листание.
    """
    t = re.sub(r"^(алиса|слушай алиса)\s+", "", _norm(text))
    has_obj = bool(re.search(r"\b(трек|песня|песню|глава|главу|часть|номер)\b", t))
    t2 = re.sub(r"\b(трек|песня|песню|глава|главу|часть|номер|пожалуйста)\b", " ", t)
    t2 = " ".join(t2.split())
    m = re.fullmatch(r"(?:(включи|поставь|запусти|вруби|переключи на|поставь на|сделай|играй)"
                     r"\s+)?(.+)", t2)
    if not m:
        return None
    verb, tail = m.group(1), m.group(2)
    if verb is None and not has_obj:
        return None
    words = [w for w in tail.split()
             if w not in ("й", "я", "ый", "ой", "ая", "ий", "го")]
    if len(words) != 1:
        return None
    w = words[0]
    # «переключи на 12» / «поставь на 12» — явный переход, слово-объект не нужно
    explicit = verb in ("переключи на", "поставь на")
    if w.isdigit() and 1 <= int(w) <= 300:
        return int(w) if (has_obj or explicit) else None
    if w in _ORDINAL:
        return _ORDINAL[w]
    # «трек номер семь»: после снятия слов «трек/номер» остаётся
    # количественное числительное — это тоже номер. Раньше работали только
    # «седьмой трек» и «трек номер 7» (аудит 22.11).
    n = _UNITS.get(w)
    if n is not None and 1 <= n <= 10:
        return int(n)
    return None


def match_loop(text: str) -> "bool | None":
    """Повтор: True — зациклить, False — выключить. None — не про повтор."""
    t = re.sub(r"^(алиса|слушай алиса)\s+", "", _norm(text))
    if re.fullmatch(r"(выключи|убери|отмени|не нужно|хватит)( это| такое)?( повтор| повторение|"
                    r"зацикливание| цикл)( пожалуйста)?"
                    r"|(не повторяй|не повторяй это|без повтора|без повторения)( пожалуйста)?", t):
        return False
    if re.search(r"\b(зацикл\w*|повторяй|по кругу|без остановки)\b", t) and \
            not re.search(r"\b(не|без)\b.*(зацикл|повтор|круг)", t):
        return True
    if re.fullmatch(r"(включи |поставь |сделай )?(повтор|повторение|зацикливание|цикл)"
                    r"( трека| музыки| песни| этого трека| альбома)?( пожалуйста)?", t):
        return True
    return None


def match_replay(text: str) -> bool:
    """«Повтори», «сначала», «сыграй заново» — текущий трек с начала один раз."""
    t = re.sub(r"^(алиса|слушай алиса)\s+", "", _norm(text))
    return bool(re.fullmatch(r"(повтори|сыграй заново|давай заново|начни заново|с начала|"
                             r"повтори (этот |текущий )?(трек|песню)?|сыграй сначала)"
                             r"( пожалуйста)?", t))


# ------------------------------------------------------------------ перемотка
_SEEK_TRIG = re.compile(
    r"\b(перемот\w*|отмот\w*|промот\w*|прокрут\w*|отскоч\w*|вперед\w*|назад|обратно)\b")


def match_seek(text: str) -> "tuple[str, float] | None":
    """Перемотка -> ("rel", ±секунды) | ("abs", секунда) | None.

    «перемотай на минуту вперёд», «отмотай тридцать секунд», «назад на
    полторы минуты», «перемотай на 2:30» (позиция от начала), «в начало».
    Без слов перемотки/направления не срабатывает: «поставь таймер на
    10 минут» и «включи третий трек» идут своими путями.
    """
    raw = text.lower().replace("ё", "е")
    t = re.sub(r"^(алиса|слушай алиса)\s+", "", _norm(text))
    if not t:
        return None
    # «перемотай на 2.5 минуты» — ПРОДОЛЖИТЕЛЬНОСТЬ, а не «мм:сс»: точка идёт
    # перед словом-единицей. Раньше общий регекс «мм:сс» принимал точку за
    # разделитель: 2.5 минуты = 125 с, 1.5 минуты = 65 с (аудит 22.11).
    # Дробь берём из СЫРОГО текста: _norm превратил бы «2.5» в «2 5» (7 минут).
    mdec = re.search(r"\bна\s+(\d{1,3})[.,](\d+)\s*(час\w*|мин\w*|сек\w*)\b", raw)
    if mdec and _SEEK_TRIG.search(t):
        word_u = mdec.group(3)
        if word_u.startswith("час"):
            unit = 3600.0
        elif word_u.startswith("мин"):
            unit = 60.0
        else:
            unit = 1.0
        value = float(f"{mdec.group(1)}.{mdec.group(2)}") * unit
        back = re.search(r"\b(назад|обратно|отмот\w*)\b", t) is not None
        return ("rel", -value if back else value)
    # абсолютная позиция «на 2:30» — только из СЫРОГО текста: _norm съедает
    # двоеточие. Двоеточие — всегда «мм:сс»; точка — только если следом НЕ
    # слово-единица (иначе это дробь, обработанная выше).
    m = re.search(r"\bна\s+(\d{1,2}):(\d{1,2})(?!\d)", raw)
    if not m:
        m = re.search(r"\bна\s+(\d{1,2})\.(\d{1,2})(?!\d)(?!\s*(?:час|мин|сек))", raw)
    if m and _SEEK_TRIG.search(t) and int(m.group(1)) * 60 + int(m.group(2)) <= 24 * 3600:
        return ("abs", float(int(m.group(1)) * 60 + int(m.group(2))))
    if re.fullmatch(r"(в|с) начал\w*( трека| песни| книги)?( пожалуйста)?", t):
        return ("abs", 0.0)
    if not _SEEK_TRIG.search(t):
        return None
    back = re.search(r"\b(назад|обратно|отмот\w*)\b", t) is not None
    dur = _parse_duration(t)
    if dur is None:
        return None
    return ("rel", -dur[0] if back else dur[0])


# ------------------------------------------------------------------ подсветка
# Светящееся кольцо: теперь есть прямые RGB-каналы в sysfs (см. leds.py),
# а на случай их отсутствия — флаг should_listen в ответе (только он
# включает кольцо «слушаю», проверено на Олеге 03.11). Фразу НЕ озвучиваем:
# само свечение и есть ответ.
@dataclass
class LightCommand:
    on: bool
    color: str = ""          # основа цвета для leds.color ('' — голубой по умолчанию)
    seconds: float = 60.0


_LIGHT_OFF_V = re.compile(
    r"^(?:выключи|погаси|убери)(?:\s+(?:подсветку|свет))?(?:\s+это)?(?:\s+пожалуйста)?$"
    r"|^(?:не свети|не светись|хватит светиться)(?:\s+пожалуйста)?$")
# «посвети» ASR часто слышит как «посвяти/посвятим» (живой случай 20.11) —
# поэтому основы, а не точные слова
_LIGHT_VERB = re.compile(
    r"^(?:посвет\w*|посвят\w*|подсвет\w*|светись|зажгись|засветись|свети)(?:\s|$)")
_LIGHT_VERB2 = re.compile(
    r"^(?:включи|зажги|сделай|поставь|вруби|поменяй|смени|измени|переключи)\b")
# слова, из которых может состоять фраза БЕЗ глагола: «зелёный цвет»,
# «а теперь синий», «на красный» (живой случай 20.11: «зелёный цвет» ушёл в LLM)
_LIGHT_FILL = {"а", "и", "теперь", "давай", "на", "в", "пожалуйста", "цвет", "свет",
               "цветом", "светом", "подсветка", "подсветку", "подсветки"}
_LIGHT_WORD = re.compile(r"\b(?:свет\w*|цвет\w*|подсветк\w*)\b")
# «включи песню свет» — это музыка, а не подсветка
_MUSIC_WORDS = re.compile(
    r"\b(?:песн\w*|трек\w*|музык\w*|радио|книг\w*|фильм\w*|сериал\w*|подкаст\w*)\b")
_GREET = re.compile(
    r"^(?:алиса|олег|слушай алиса|привет|здравствуй(?:те)?|добрый день|"
    r"добрый вечер|доброе утро|ну давай)\s+")


def match_light(text: str) -> "LightCommand | None":
    """Подсветка: LightCommand (вкл/выкл, цвет, длительность) или None.

    Голосом фраза приходит с перебивками: «Алиса привет посвятим красным»,
    «включи красный цвет», «сделай свет зелёным». Всё это — подсветка.
    """
    t = _norm(text)
    while True:                         # «Алиса привет …» — снимаем приветствия
        new = _GREET.sub("", t)
        if new == t:
            break
        t = new
    if not t:
        return None
    if _LIGHT_OFF_V.fullmatch(t):
        return LightCommand(False)
    if _MUSIC_WORDS.search(t):
        return None
    from .leds import find_color
    color = find_color(t)
    words = t.split()
    # фраза только из цвета и служебных слов: «зелёный цвет», «а теперь синий»
    bare = bool(color) and len(words) <= 4 and all(
        w in _LIGHT_FILL or color in w for w in words)
    is_light = bool(
        bare
        or _LIGHT_VERB.match(t)
        or (_LIGHT_VERB2.match(t) and (_LIGHT_WORD.search(t) or color))
    )
    if not is_light:
        return None
    dur = _parse_duration(t)
    seconds = dur[0] if dur else 60.0
    return LightCommand(True, color, max(5.0, min(3600.0, seconds)))


# ------------------------------------------------------------------ погода / курс валют
_WEATHER_Q = re.compile(
    r"\bпогод\w*|\bтемператур\w*|\bсколько (?:сейчас )?(?:на улице|градусов)|"
    r"\bна улице (?:тепло|холодно|жарко|мороз)\w*|"
    r"\b(?:будет|пойд[её]т|идет|идёт) ли\b[^.!?]{0,24}\b(?:дожд\w*|снег\w*)|"
    r"\bнужен ли зонт|\bзонт\w*", re.I)

# после «в/во» город тянется до служебного слова («погода в Москве на завтра»)
_CITY_STOP = (r"(?:погод\w*|температур\w*|завтра|сегодня|сейчас|утром|дн[её]м|"
              r"вечером|ночью|будет|пойд[её]т|ид[её]т|осадк\w*|на|и)\b")


def match_weather(text: str) -> "tuple[str, str] | None":
    """Погода -> (kind, город) | None. kind: now | tomorrow | rain; город "" — дома."""
    t = re.sub(r"^(алиса|слушай алиса)\s+", "", _norm(text))
    if not t or not _WEATHER_Q.search(t):
        return None
    # «включи песню погода», «почему погода меняется» — не наш случай
    if re.search(r"\b(включи|поставь|запусти|вруби)\b", t):
        return None
    if re.match(r"(почему|зачем|отчего)\b", t):
        return None
    if re.search(r"\bзавтра\b", t):
        kind = "tomorrow"
    elif re.search(r"\b(дожд\w*|снег\w*|зонт\w*|осадк\w*)", t):
        kind = "rain"
    else:
        kind = "now"
    city = ""
    m = re.search(r"\b(?:в|во)\s+([а-яё][а-яё\-\s]{1,40}?)(?=\s+" + _CITY_STOP + r"|$)", t)
    if m:
        city = m.group(1).strip()
        city = re.sub(r"^(?:городе|город)\s+", "", city).strip()
        # «в москве» — падеж разбирает weather_lite (словарь + эвристика)
    return kind, city


_RATE_Q = re.compile(
    r"\bкурс\w*|\bсколько (?:стои\w*|дают|дадут)\b|\bпоч[её]м\b|\bбакс\w*", re.I)
_RATE_CUR = re.compile(r"\b(доллар\w*|бакс\w*)\b", re.I)


def match_rates(text: str) -> str | None:
    """Курс валют -> USD | EUR | CNY | all | None."""
    t = re.sub(r"^(алиса|слушай алиса)\s+", "", _norm(text))
    if not t:
        return None
    # «включи/поставь …» — это музыка, а не курс, даже если в названии есть
    # «доллар» или «курс»
    if re.search(r"\b(включи|поставь|запусти|вруби)\b", t):
        return None
    cur = None
    if _RATE_CUR.search(t):
        cur = "USD"
    elif re.search(r"\bевро\b", t):
        cur = "EUR"
    elif re.search(r"\bюан\w*", t):
        cur = "CNY"
    if cur is None:
        # «курс валют», «какой курс» — оба основных
        return "all" if re.search(r"\bкурс\w*", t) else None
    return cur


